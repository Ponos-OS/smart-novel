package main

import (
	"encoding/json"
	"fmt"
	"strings"
)

const header = "Code generated by tools/genshared from spec/shared.json. DO NOT EDIT."

func quote(value string) string {
	var encoded strings.Builder
	encoder := json.NewEncoder(&encoded)
	encoder.SetEscapeHTML(false)
	_ = encoder.Encode(value)
	inner := strings.TrimSpace(encoded.String())
	inner = strings.Trim(inner, `"`)

	return "'" + strings.NewReplacer(`\"`, `"`, `'`, `\'`).Replace(inner) + "'"
}

func tsDoc(description string) string {
	if description == "" {
		return ""
	}

	return fmt.Sprintf("/** @description %s */\n", description)
}

func renderTypeScript(s *spec) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n", header)

	for _, i := range s.Integers {
		fmt.Fprintf(&b, "\n%sexport const %s = %d;\n", tsDoc(i.Description), i.Name, i.Value)
	}
	for _, e := range s.Errors {
		fmt.Fprintf(&b, "\n%sexport const %s = %s;\n", tsDoc(e.Description), e.Code, quote(e.Code))
		if e.Message != "" {
			fmt.Fprintf(&b, "\nexport const %s_MESSAGE = %s;\n", e.Code, quote(e.Message))
		}
	}
	for _, m := range s.StringMaps {
		fmt.Fprintf(&b, "\n%sexport const %s: Readonly<Record<string, string>> = {\n", tsDoc(m.Description), m.Name)
		for _, e := range m.Entries {
			fmt.Fprintf(&b, "  %s: %s,\n", quote(e.Key), quote(e.Value))
		}
		b.WriteString("};\n")
	}

	fmt.Fprintf(&b, "\n%sexport enum Role {\n", tsDoc(s.Roles.Description))
	for _, r := range s.Roles.Levels {
		fmt.Fprintf(&b, "  %s = %s,\n", r.Name, quote(r.Name))
	}
	b.WriteString("}\n\n/** @description Higher number = more privileges. */\nexport const ROLE_HIERARCHY: Record<Role, number> = {\n")
	for _, r := range s.Roles.Levels {
		fmt.Fprintf(&b, "  [Role.%s]: %d,\n", r.Name, r.Level)
	}
	b.WriteString("};\n")

	for _, p := range s.Patterns {
		fmt.Fprintf(&b, "\n%sexport const %s = new RegExp(%s);\n", tsDoc(p.Description), p.Name, quote(p.Source))
	}

	b.WriteString("\nexport type PenNameProblem =")
	for _, p := range s.PenNameProblems {
		fmt.Fprintf(&b, "\n  | %s", quote(p.Code))
	}
	b.WriteString(";\n\nexport const PEN_NAME_PROBLEM_MESSAGES: Record<PenNameProblem, string> = {\n")
	for _, p := range s.PenNameProblems {
		fmt.Fprintf(&b, "  %s: %s,\n", p.Code, quote(p.Message))
	}
	b.WriteString("};\n")

	return b.String()
}
